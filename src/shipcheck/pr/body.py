"""Branch naming, PR title and the evidence-rich PR body (FR-7)."""

from __future__ import annotations

import re
from pathlib import PurePosixPath

from shipcheck.contracts.finding import Finding

NEVER_MERGE_NOTE = "> **ShipCheck never auto-merges — a human reviewer makes the final call.**"


def _slug(text: str) -> str:
    """Lowercase, hyphenated, filesystem/ref-safe slug."""
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s or "finding"


def branch_name(finding: Finding) -> str:
    """shipcheck/fix-<class>-<file-stem>-<short-id>  (a valid git ref)."""
    stem = PurePosixPath(finding.target.file).stem
    short_id = finding.finding_id.split("-")[-1][:8]
    return f"shipcheck/fix-{finding.vuln_class.value}-{_slug(stem)}-{short_id}"


def pr_title(finding: Finding) -> str:
    return f"[ShipCheck] Fix {finding.vuln_class.value} in {finding.target.file}"


def _diff_block(finding: Finding) -> str:
    """Render the fix hunks as a readable diff-style block."""
    fix = finding.fix
    if not fix or not fix.hunks:
        return "_No patch hunks._"
    lines = []
    for h in fix.hunks:
        lines.append(f"--- a/{h.file}")
        lines.append(f"+++ b/{h.file}")
        for ln in h.search.splitlines():
            lines.append(f"- {ln}")
        for ln in h.replace.splitlines():
            lines.append(f"+ {ln}")
    return "```diff\n" + "\n".join(lines) + "\n```"


def render_pr_body(finding: Finding, *, repo: str = "") -> str:
    """Build the evidence-first PR body (FR-7 template)."""
    verdict = finding.verdict
    evidence = finding.evidence
    fix = finding.fix

    score = verdict.score if verdict else finding.score
    severity = finding.severity.value if hasattr(finding.severity, "value") else str(finding.severity)

    parts = [
        f"## 🛡️ ShipCheck — confirmed {finding.vuln_class.value} vulnerability",
        "",
        f"**Risk score:** {score}/100 ({severity})",
        "",
        NEVER_MERGE_NOTE,
        "",
        "### 1. Exploit evidence",
    ]
    if evidence:
        parts += [
            f"- **Payload:** `{evidence.payload}`",
            f"- **Observed marker:** `{evidence.matched_text or evidence.target_marker}` "
            f"(verdict: **{evidence.verdict.value}**)",
            f"- **Response status:** `{evidence.response_status}`",
            "",
            "<details><summary>Response excerpt</summary>",
            "",
            "```",
            (evidence.response_excerpt or "")[:1000],
            "```",
            "</details>",
        ]
    else:
        parts.append("_No captured evidence._")

    parts += ["", "### 2. Root cause", (fix.root_cause if fix and fix.root_cause else "_n/a_")]
    parts += ["", "### 3. Fix", (fix.explanation if fix and fix.explanation else ""), "", _diff_block(finding)]

    parts += ["", "### 4. Re-verification"]
    if fix:
        marker_line = "✅ marker **absent**" if fix.recheck_attack_marker_absent else "❌ marker still present"
        tests_line = "✅ repo tests **passed**" if fix.repo_tests_passed else "❌ repo tests failed"
        parts += [
            f"- Re-ran the exact exploit on the patched code: {marker_line}",
            f"- Repo test suite: {tests_line}",
        ]
    else:
        parts.append("_No fix verification recorded._")

    parts += [
        "",
        "### 5. Reviewer checklist",
        "- [ ] The patch addresses the root cause, not just the symptom",
        "- [ ] No unrelated code was changed",
        "- [ ] The existing tests remain meaningful",
        "- [ ] Safe to merge",
    ]
    if repo:
        parts += ["", f"<sub>Generated by ShipCheck for `{repo}`.</sub>"]
    return "\n".join(parts)
